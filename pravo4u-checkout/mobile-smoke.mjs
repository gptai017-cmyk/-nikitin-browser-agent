import {webkit, devices} from "playwright";
import assert from "node:assert/strict";
import {mkdirSync} from "node:fs";
const ROOT="https://pravo4u-max.cbd-legal-cloudflare-worker.workers.dev";
mkdirSync("/tmp/pravo-mobile",{recursive:true});
const browser=await webkit.launch({headless:true});
const ctx=await browser.newContext({...devices["iPhone 13"],acceptDownloads:true});
const page=await ctx.newPage();
const browserErrors=[],sensitive=[];
page.on("pageerror",e=>browserErrors.push(String(e)));
page.on("request",r=>{
 const data=r.postData();
 if(data && /SECRET_LOCAL_PASSPORT_2026/.test(data))sensitive.push(r.url());
});
let index=await page.goto(ROOT+"/store",{waitUntil:"domcontentloaded",timeout:30000});
assert.equal(index.status(),200);
assert.match(await page.locator("body").innerText(),/Магазин|ПРАВО4U/);
await page.screenshot({path:"/tmp/pravo-mobile/catalog-iphone13.png",fullPage:true});
const list=["order","rent","loan","service","fssp_minimum","course_refund","fssp_files","fssp_copy","fssp_complaint","court_files","loan_demand","service_end","service_claim","online_return","defect_return","prepayment_delay","work_contract","goods_sale","vehicle_sale","rent_return","service_advance"];
for(const key of list){
 const result=await page.goto(ROOT+"/compose?type="+key,{waitUntil:"load",timeout:30000});
 assert.equal(result.status(),200,key+" failed page HTTP");
 await page.waitForFunction(()=>document.querySelectorAll("#form .fgroup").length>0,{timeout:10000});
 assert.ok(await page.locator("#form .fgroup").count()>=4,"Missing fields "+key);
 assert.equal(await page.locator("#make").isVisible(),true,"Missing create button "+key);
 const metrics=await page.evaluate(()=>({width:document.documentElement.scrollWidth,viewport:window.innerWidth}));
 assert.ok(metrics.width<=metrics.viewport+3,"Horizontal overflow on mobile "+key+" "+JSON.stringify(metrics));
}
await page.goto(ROOT+"/compose?type=order",{waitUntil:"load"});
await page.waitForSelector("#court");
const input={court:"Мировой судья судебного участка №1",case:"2-111/2026",date:"01.10.2026",full:"Тестовый Истец",address:"г. Пенза",creditor:"Тестовый Банк",sum:"10000",receiptdate:"02.10.2026"};
for(const [k,v]of Object.entries(input))await page.locator("#"+k).fill(v);
await page.locator("#received").selectOption("received");
await page.locator("#late").selectOption("no");
const event=page.waitForEvent("download");
await page.locator("#make").click();
const download=await event;
assert.match(download.suggestedFilename(),/\.docx$/);
await download.saveAs("/tmp/pravo-mobile/order-ios.docx");
await page.screenshot({path:"/tmp/pravo-mobile/order-iphone13.png",fullPage:true});
await page.goto(ROOT+"/compose?type=rent",{waitUntil:"load"});
await page.waitForSelector("#landlord_passport");
await page.locator("#landlord_passport").fill("SECRET_LOCAL_PASSPORT_2026");
await page.locator("#tenant_passport").fill("SECRET_LOCAL_PASSPORT_2026");
await page.screenshot({path:"/tmp/pravo-mobile/rent-fields-iphone13.png",fullPage:false});
assert.deepEqual(sensitive,[],"Personal information was transmitted!");
assert.deepEqual(browserErrors,[],"Unhandled browser errors");
await browser.close();
console.log("WEBKIT MOBILE PASS: "+list.length+" forms, Word download and no field upload; physical iPhone NOT tested.");
