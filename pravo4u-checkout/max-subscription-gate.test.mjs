import assert from 'node:assert/strict';
import fs from 'node:fs';
const raw=fs.readFileSync('pravo4u-max/subscription-gate.js','utf8');
const {channelGate,channelSettings,documentMenu}=await import('data:text/javascript;base64,'+Buffer.from(raw).toString('base64'));
const ROOT='https://pravo4u-max.cbd-legal-cloudflare-worker.workers.dev';
const reply={text:'Документы',buttons:[[{type:'link',text:'ДКП',url:ROOT+'/compose?type=land_sale'}]]};
assert.ok(documentMenu(reply));
assert.ok(!documentMenu({buttons:[[{type:'link',url:'https://t.me/pravo4urus'}]]}));
assert.equal(channelSettings({}),null);
assert.equal(await channelGate({},123,reply,async()=>{throw Error('API should not be called')}),reply);
const env={MAX_CHANNEL_CHAT_ID:'12345678',MAX_CHANNEL_URL:'https://max.ru/channel_pravo4u'};
let path='';
const yes=await channelGate(env,123,reply,async(_,verb,url)=>{path=url;assert.equal(verb,'GET');return {members:[{user_id:123}]}});
assert.equal(yes,reply);
assert.equal(path,'/chats/12345678/members?user_ids=123');
const no=await channelGate(env,123,reply,async()=>({members:[]}));
assert.match(no.text,/подпишитесь/i);
assert.equal(no.buttons[0][0].url,env.MAX_CHANNEL_URL);
const err=await channelGate(env,123,reply,async()=>{throw Error('network broken')});
assert.match(err.text,/временно недоступна/i);
const x=await channelGate(env,123,{text:'Выберите тему',buttons:[]},async()=>{throw Error('not required')});
assert.equal(x.text,'Выберите тему');
assert.throws(()=>channelSettings({MAX_CHANNEL_CHAT_ID:'abc',MAX_CHANNEL_URL:'https://max.ru/channel'}),/invalid/);
assert.throws(()=>channelSettings({MAX_CHANNEL_CHAT_ID:'123',MAX_CHANNEL_URL:'https://evil.ru/channel'}),/invalid/);
console.log('MAX channel stateless subscriber gating PASS (inactive before actual channel creation)');
